"""3D models: stock-library overrides + syncing them into a built .kicad_pcb.

Two problems this solves, for both projects (the sensor board imports this
module off ../../kicad/gen like the rest of the shared generator):

1. **Stock footprints with no stock model.**  KiCad 10 ships the JST *ZH*
   footprints but no ZH 3D models (Connector_JST.3dshapes has EH/GH/PH/SH/XH
   only), and OptoDevice/AMS_TSL25911FN points at a DFN-6 model that isn't in
   the library either.  Their footprints therefore carry a `(model ...)` line
   whose file does not exist, and the parts render as bare pads.  `OVERRIDES`
   below re-points them at models kept in each project's `3d/`.

2. **Keeping an already-routed board in sync.**  `pcb_build.py` regenerates
   the PCB from scratch, which is not something you can do to a hand-routed
   board.  `sync_pcb()` therefore patches only the `(model ...)` blocks of an
   existing .kicad_pcb in place, taking each footprint's models from the
   project's own .pretty (the generator's source of truth) or from
   `OVERRIDES`, and leaving every other byte of the file alone.

       python3 models3d.py ../clock.kicad_pcb

Model placement convention (KiCad's 3D frame): X = footprint X, **Y = minus
footprint Y**, Z up out of the mounting side, offsets in mm applied after the
rotation, and each `(rotate (xyz a b c))` value is applied as a *negative*
rotation about that axis, X first, then Y, then Z.
"""
import os
import re
import sys

# footprint name (no library nickname) -> (path, offset xyz, rotate xyz)
OVERRIDES = {
    # generated by mk3d_jst_zh.py, already in the KiCad 3D frame
    "JST_ZH_B2B-ZR_1x02_P1.50mm_Vertical": (
        "${KIPRJMOD}/3d/JST_ZH_B2B-ZR_1x02_P1.50mm_Vertical.step",
        (0, 0, 0), (0, 0, 0)),
    "JST_ZH_B6B-ZR_1x06_P1.50mm_Vertical": (
        "${KIPRJMOD}/3d/JST_ZH_B6B-ZR_1x06_P1.50mm_Vertical.step",
        (0, 0, 0), (0, 0, 0)),
    # ams SON-06-FN (TSL2591) package model, ams part 2000x2400: origin at the
    # package centre on the seating plane, pin-1 dot over the -x/+y pad, so it
    # drops straight onto the stock land pattern.
    "AMS_TSL25911FN": (
        "${KIPRJMOD}/3d/AMS_TSL25911FN.step", (0, 0, 0), (0, 0, 0)),
}


def _fmt(v):
    return " ".join(f"{x:g}" for x in v)


def model_block(path, offset, rotate, indent="\t\t"):
    i = indent
    return (f'{i}(model "{path}"\n'
            f'{i}\t(offset\n{i}\t\t(xyz {_fmt(offset)})\n{i}\t)\n'
            f'{i}\t(scale\n{i}\t\t(xyz 1 1 1)\n{i}\t)\n'
            f'{i}\t(rotate\n{i}\t\t(xyz {_fmt(rotate)})\n{i}\t)\n'
            f'{i})\n')


# --- s-expression surgery -------------------------------------------------

def _blocks(txt, tag="\n\t(footprint "):
    """Yield (start, end) of every top-level footprint block."""
    i = 0
    while True:
        i = txt.find(tag, i)
        if i < 0:
            return
        j, depth = i + len(tag) - len("(footprint "), 0
        while True:
            c = txt[j]
            if c == '"':
                j += 1
                while txt[j] != '"' or txt[j - 1] == "\\":
                    j += 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        yield i, j + 1
        i = j


def _models_of(seg):
    """(start, end) of the run of (model ...) sub-blocks, or None."""
    spans = []
    for m in re.finditer(r"\n\t\t\(model ", seg):
        j, depth = m.start() + 2, 0
        while True:
            c = seg[j]
            if c == '"':
                j += 1
                while seg[j] != '"' or seg[j - 1] == "\\":
                    j += 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        end = j + 2 if seg[j + 1:j + 2] == "\n" else j + 1
        spans.append((m.start() + 1, end))
    return (spans[0][0], spans[-1][1]) if spans else None


def _lib_model(pretty_dir, fp_name):
    """The (model ...) text of a project footprint, re-indented for the PCB."""
    path = os.path.join(pretty_dir, fp_name + ".kicad_mod")
    if not os.path.exists(path):
        return None
    seg = "\n" + open(path).read()
    spans = []
    for m in re.finditer(r"\n\t\(model ", seg):
        j, depth = m.start() + 1, 0
        while True:
            c = seg[j]
            if c == '"':
                j += 1
                while seg[j] != '"' or seg[j - 1] == "\\":
                    j += 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        spans.append(seg[m.start() + 1:j + 1])
    if not spans:
        return None
    txt = "".join("\t" + ln if ln.strip() else ln
                  for s in spans for ln in s.splitlines(True))
    return txt if txt.endswith("\n") else txt + "\n"


def sync_pcb(pcb_path, verbose=True):
    """Rewrite every footprint's (model ...) from the .pretty / OVERRIDES."""
    proj = os.path.dirname(os.path.abspath(pcb_path))
    txt = open(pcb_path).read()
    out, prev, n = [], 0, 0
    for start, end in _blocks(txt):
        seg = txt[start:end]
        lib_id = re.match(r'\n\t\(footprint "([^"]+)"', seg).group(1)
        nick, _, fp_name = lib_id.rpartition(":")
        ref = re.search(r'\(property "Reference" "([^"]+)"', seg).group(1)
        if fp_name in OVERRIDES:
            block = model_block(*OVERRIDES[fp_name])
        else:
            block = _lib_model(os.path.join(proj, nick + ".pretty"), fp_name)
        if block is None:
            continue
        span = _models_of(seg)
        if span and seg[span[0]:span[1]] == block:
            continue
        if span:
            new = seg[:span[0]] + block + seg[span[1]:]
        else:  # insert before the footprint's closing paren
            k = seg.rstrip().rfind("\n")
            new = seg[:k + 1] + block + seg[k + 1:]
        out.append(txt[prev:start])
        out.append(new)
        prev = end
        n += 1
        if verbose:
            path = re.search(r'\(model "([^"]+)"', block).group(1)
            print(f"  {ref:5s} {fp_name:45s} -> {os.path.basename(path)}"
                  f"{' (replaced)' if span else ''}")
    out.append(txt[prev:])
    if n:
        open(pcb_path, "w").write("".join(out))
    if verbose:
        print(f"{os.path.basename(pcb_path)}: {n} footprint(s) updated")
    return n


# --- pcbnew side (used by pcb_build.py when regenerating from scratch) -----

def apply_override(fp):
    """Give a freshly loaded stock footprint its project 3D model."""
    import pcbnew
    name = fp.GetFPID().GetLibItemName()
    spec = OVERRIDES.get(str(name))
    if spec is None:
        return False
    path, offset, rotate = spec
    models = fp.Models()
    models.clear()
    m = pcbnew.FP_3DMODEL()
    m.m_Filename = path
    m.m_Offset = pcbnew.VECTOR3D(*[float(v) for v in offset])
    m.m_Rotation = pcbnew.VECTOR3D(*[float(v) for v in rotate])
    m.m_Scale = pcbnew.VECTOR3D(1.0, 1.0, 1.0)
    m.m_Show = True
    models.push_back(m)
    return True


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sync_pcb(sys.argv[1])
